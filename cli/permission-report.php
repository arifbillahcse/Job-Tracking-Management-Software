<?php

declare(strict_types=1);

/**
 * Print the role x permission and role x route matrix as Markdown, straight from the database and the
 * route table, so the documentation cannot drift from what the application actually enforces.
 *
 *   php cli/permission-report.php > docs/permission-matrix.md
 */

if (PHP_SAPI !== 'cli') {
    exit(1);
}

require dirname(__DIR__) . '/app/bootstrap.php';

use App\Core\App;
use App\Core\Router;
use App\Repositories\RoleRepository;

App::boot();

$repo = new RoleRepository();
$roles = $repo->allWithCounts();
$granted = [];
foreach ($roles as $role) {
    $granted[(int) $role['id']] = array_flip($repo->permissionKeys((int) $role['id']));
}

$tick = static fn (bool $yes): string => $yes ? 'yes' : '-';
$names = array_map(static fn (array $r): string => (string) $r['name'], $roles);

echo "# Permission matrix\n\n";
echo "Generated by `php cli/permission-report.php` from the live database and route table. ";
echo "Roles shown are the ones in the database when it was generated; the built-in **Admin** role always holds everything.\n\n";

echo "## Role x permission\n\n";
echo '| Area | Permission | What it allows | ' . implode(' | ', $names) . " |\n";
echo '|---|---|---|' . str_repeat('---|', count($names)) . "\n";
foreach ($repo->allPermissions() as $permission) {
    $cells = array_map(static fn (array $r): string => $tick(isset($granted[(int) $r['id']][$permission['name']])), $roles);
    echo "| {$permission['group_name']} | `{$permission['name']}` | {$permission['description']} | " . implode(' | ', $cells) . " |\n";
}

$router = new Router();
(require BASE_PATH . '/app/Config/routes.php')($router);

echo "\n## Role x route\n\n";
echo "`public` = anyone, `signed in` = any signed-in user, otherwise the permission key that is required. ";
echo "Some routes add finer rules inside the service (for example a status change checks the permission of that particular transition, ";
echo "and user administration only lets you manage users whose permissions you hold yourself).\n\n";
echo '| Method | Path | Requires | ' . implode(' | ', $names) . " |\n";
echo '|---|---|---|' . str_repeat('---|', count($names)) . "\n";
foreach ($router->routes() as $route) {
    $requires = $route->isPublic ? 'public' : ($route->permission ?? 'signed in');
    $cells = [];
    foreach ($roles as $role) {
        $allowed = $route->isPublic || $route->permission === null || isset($granted[(int) $role['id']][$route->permission]);
        $cells[] = $tick($allowed);
    }
    echo "| {$route->method} | `{$route->pattern}` | " . ($route->isPublic || $route->permission === null ? $requires : "`{$requires}`") . ' | ' . implode(' | ', $cells) . " |\n";
}
